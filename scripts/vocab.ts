// The glossary (src/content/terms/terms.yaml) is the one source of the house
// vocabulary: every term is accepted by Vale, and every word a term replaces
// is flagged. Run by `vocab`, and by `prose` before Vale.
import { parse } from "yaml";

type Term = { id: string; term: string; lowercase?: boolean; insteadOf?: string[] };

const terms = parse(await Bun.file("src/content/terms/terms.yaml").text()) as Term[];
const header = "# Generated by scripts/vocab.ts from src/content/terms/terms.yaml; do not edit.\n";

// A term may open a sentence capitalized, unless it is a name kept lowercase.
const accept = [
  ...new Set(terms.map((t) => (t.lowercase ? t.term : `[${t.term[0].toUpperCase()}${t.term[0]}]${t.term.slice(1)}`))),
].sort();
await Bun.write("styles/config/vocabularies/Flywheel/accept.txt", `${accept.join("\n")}\n`);

const swaps = terms.flatMap((t) => (t.insteadOf ?? []).map((w) => `  '${w}': '${t.term}'`));
await Bun.write(
  "styles/Flywheel/Terms.yml",
  `${header}extends: substitution
message: "Use '%s' instead of '%s'; see the glossary."
level: warning
ignorecase: false
swap:
${swaps.join("\n")}
`,
);

console.log(`vocab: ${accept.length} terms accepted, ${swaps.length} substitutions`);
